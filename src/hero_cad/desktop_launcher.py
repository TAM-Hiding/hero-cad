"""Per-user desktop integration for the current editable/venv installation."""
import argparse
import json
import os
from pathlib import Path
import sys
import tempfile
import xml.etree.ElementTree as ET


MARKER = 'X-HERO-CAD-Managed=true'


def data_directory():
    value = os.environ.get('XDG_DATA_HOME', '')
    return Path(value) if value and Path(value).is_absolute() else Path.home()/'.local/share'


def desktop_string(value):
    value = str(value)
    if any(ord(c) < 32 for c in value):
        raise ValueError('Launcher paths cannot contain control characters')
    return value.replace('\\', '\\\\').replace('\t', '\\t')


def exec_argument(value):
    # Desktop string unescaping precedes Exec argument unquoting. Never a shell.
    value = desktop_string(value).replace('\\', '\\\\')
    for character in ('"', '`', '$'):
        value = value.replace(character, '\\\\'+character)
    return '"'+value.replace('%', '%%')+'"'


def icon_destination(icon, data_home):
    icon = Path(icon).expanduser().absolute()
    if not icon.is_file() or icon.stat().st_size > 8*1024*1024:
        raise ValueError('Supply the approved square HERO-CAD PNG or SVG artwork (up to 8 MiB) with --icon')
    if icon.suffix.lower() == '.png':
        from PySide6.QtGui import QImage
        image = QImage(str(icon))
        if image.isNull() or image.width() != image.height() or not 32 <= image.width() <= 4096:
            raise ValueError('The approved PNG must be square, 32–4096 pixels; 512×512 is recommended')
        folder, suffix = f'{image.width()}x{image.height()}', '.png'
    elif icon.suffix.lower() == '.svg':
        root = ET.parse(icon).getroot()
        if root.tag != '{http://www.w3.org/2000/svg}svg':
            raise ValueError('Expected an SVG image')
        box = root.get('viewBox', '').replace(',', ' ').split()
        if len(box) != 4 or not 0 < float(box[2]) == float(box[3]) <= 100000:
            raise ValueError('The approved SVG must have a square positive viewBox')
        folder, suffix = 'scalable', '.svg'
    else:
        raise ValueError('Use the approved PNG or SVG logo; no replacement artwork is bundled')
    return icon, data_home/'icons/hicolor'/folder/'apps'/('hero-cad'+suffix)


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def managed_paths(data_home):
    manifest = data_home/'hero-cad/launcher.json'
    if not manifest.exists():
        return []
    values = json.loads(manifest.read_text())
    result = []
    for value in values:
        path = Path(value)
        try:
            parts = path.relative_to(data_home).parts
        except ValueError:
            raise ValueError('Launcher manifest contains an unrelated path') from None
        icon = (len(parts) == 5 and parts[:2] == ('icons', 'hicolor')
                and parts[3] == 'apps' and parts[4] in ('hero-cad.png', 'hero-cad.svg'))
        if not icon and parts not in (('applications', 'hero-cad.desktop'), ('hero-cad', 'launch.py')):
            raise ValueError('Launcher manifest contains an unrelated path')
        result.append(path)
    return result


def install_launcher(icon, *, python=None, data_home=None):
    data_home = Path(data_home).absolute() if data_home is not None else data_directory()
    # Preserve venv paths even when its Python executable is a symlink.
    python = Path(python or sys.executable).absolute()
    entrypoint = python.parent/'hero-cad'
    if not python.is_file() or not os.access(python, os.X_OK) or not entrypoint.is_file():
        raise ValueError('Install HERO-CAD into this Python environment first: python -m pip install --no-deps -e .')
    source_icon, installed_icon = icon_destination(icon, data_home)
    desktop = data_home/'applications/hero-cad.desktop'
    if desktop.exists() and MARKER not in desktop.read_text():
        raise ValueError('An unmanaged hero-cad.desktop already exists; back it up or move it before setup')
    previous = managed_paths(data_home)
    wrapper = data_home/'hero-cad/launch.py'
    # Paths are Python literals; Exec invokes a specific interpreter, not a shell.
    script = f'''# Generated by hero-cad-install-launcher. Re-run setup after moving/rebuilding the environment.
import os
from pathlib import Path
import sys
state = os.environ.get('XDG_STATE_HOME', '')
state = Path(state) if state and Path(state).is_absolute() else Path.home()/'.local/state'
log = state/'hero-cad/launcher.log'
log.parent.mkdir(parents=True, exist_ok=True)
stream = os.open(log, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
os.dup2(stream, 1)
os.dup2(stream, 2)
os.close(stream)
os.environ.setdefault('QT_QPA_PLATFORM', 'xcb')
os.environ['HERO_CAD_ICON'] = {str(installed_icon)!r}
try:
    os.execv({str(python)!r}, [{str(python)!r}, {str(entrypoint)!r}])
except OSError as error:
    print('HERO-CAD launcher failed:', error, file=sys.stderr)
    print('Re-run hero-cad-install-launcher from the current virtual environment.', file=sys.stderr)
    sys.exit(1)
'''
    contents = '\n'.join((
        '[Desktop Entry]', 'Type=Application', 'Version=1.0', 'Name=HERO-CAD',
        'GenericName=Parametric Mechanical CAD', 'Comment=Offline parametric mechanical modeling',
        'Exec=/usr/bin/env '+exec_argument(python)+' '+exec_argument(wrapper),
        'Icon='+desktop_string(installed_icon), 'Terminal=false',
        'Categories=Graphics;Engineering;', 'StartupWMClass=hero-cad', 'StartupNotify=false', MARKER, ''))
    # Validate every path/string before changing the installed integration.
    icon_bytes = source_icon.read_bytes()
    atomic_write(installed_icon, icon_bytes)
    atomic_write(wrapper, script.encode())
    atomic_write(desktop, contents.encode())
    tracked = sorted(set(previous+[desktop, wrapper, installed_icon]), key=str)
    atomic_write(data_home/'hero-cad/launcher.json', json.dumps(list(map(str, tracked)), indent=2).encode())
    return desktop


def uninstall_launcher(*, data_home=None):
    data_home = Path(data_home).absolute() if data_home is not None else data_directory()
    paths = managed_paths(data_home)
    desktop = data_home/'applications/hero-cad.desktop'
    if desktop.exists() and MARKER not in desktop.read_text():
        raise ValueError('Refusing to remove an unmanaged desktop entry')
    for path in paths:
        path.unlink(missing_ok=True)
    (data_home/'hero-cad/launcher.json').unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Install/update the per-user HERO-CAD desktop launcher using approved artwork.')
    parser.add_argument('--icon', type=Path, help='Approved square PNG or SVG logo (required for installation)')
    parser.add_argument('--uninstall', action='store_true', help='Remove only files created by launcher setup')
    args = parser.parse_args(argv)
    try:
        if args.uninstall:
            uninstall_launcher()
            print('Removed the per-user HERO-CAD launcher; documents and preferences are unchanged.')
        else:
            if args.icon is None:
                parser.error('--icon is required: supply the approved HERO-CAD logo; see docs/DESKTOP_LAUNCHER.md')
            path = install_launcher(args.icon)
            print(f'Installed {path}\nOpen Ubuntu Applications, search HERO-CAD, launch it, then pin it to the dock.')
        return 0
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, f'HERO-CAD launcher setup: {error}\n')


if __name__ == '__main__':
    raise SystemExit(main())
